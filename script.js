const form = document.getElementById("quizForm");

questions.forEach((q, index) => {
  const div = document.createElement("div");
  div.className = "question";
  div.id = "q" + index;
  div.innerHTML = `<p>${q.q}</p>` + q.options.map((opt, i) =>
    `<label><input type="radio" name="q${index}" value="${i}"> ${opt}</label><br>`
  ).join("") + `<div class="feedback" id="feedback${index}"></div>`;
  form.appendChild(div);
});

document.getElementById("submit").onclick = function() {
  let correct = 0;

  questions.forEach((q, index) => {
    const selected = document.querySelector(`input[name="q${index}"]:checked`);
    const feedback = document.getElementById(`feedback${index}`);
    const container = document.getElementById(`q${index}`);
    if (!selected) {
      container.className = "question incorrect";
      feedback.innerHTML = `لم تقم باختيار إجابة.`;
      return;
    }

    if (parseInt(selected.value) === q.answer) {
      correct++;
      container.className = "question correct";
      feedback.innerHTML = `إجابة صحيحة.`;
    } else {
      container.className = "question incorrect";
      feedback.innerHTML = `إجابة خاطئة. الإجابة الصحيحة هي: <span class="correct-answer">${q.options[q.answer]}</span>`;
    }
  });

  const percentage = Math.round((correct / questions.length) * 100);
  const progress = document.getElementById("progress");
  progress.style.width = percentage + "%";
  progress.innerText = `${percentage}%`;
  progress.style.backgroundColor = percentage >= 75 ? "#28a745" : percentage >= 50 ? "#ffc107" : "#dc3545";
};
